"""Generated deployment files: the agent image's Dockerfile, the Compose file, the
Kubernetes manifests (+ an OpenShift Route) and the image-loader DaemonSet. Every
target writes what it renders to `work/deploy/` before using it, so `evalbuilder
deploy render` shows exactly what will run.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from evalbuilder.deploy.spec import DeploymentSpec

LOADER_SUFFIX = "-image-loader"
HEALTH_PROBE = "import sys, urllib.request; sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:{port}/health', timeout=3).status == 200 else 1)"


def package_dir(module: str) -> str:
    """The path copied into the image for a target module: its top-level package
    directory (`examples.weather_bot.agent` → `examples`), or `<module>.py` for a
    single-file module."""
    head = module.split(".", 1)[0]
    return head if "." in module else f"{head}.py"


def server_env(spec: DeploymentSpec) -> dict[str, str]:
    """Container environment: the user's variables plus the model specs the server reads."""
    env = dict(spec.env)
    if spec.agent_model:
        env["EVALBUILDER_AGENT_MODEL"] = spec.agent_model
    if spec.mock_model:
        env["EVALBUILDER_MOCK_MODEL"] = spec.mock_model
    return env


def render_dockerfile(spec: DeploymentSpec) -> str:
    extras = ",".join(sorted({e for e in spec.extras if e}))
    install = f'.[{extras}]' if extras else "."
    lines = [
        "# Generated by evalbuilder deploy — the target agent with both mock layers behind `evalbuilder serve`.",
        "# Build context: the evalbuilder checkout (src/) plus the target's package. Rebuild after changing either.",
        f"FROM python:{spec.python_version}-slim",
        "ENV PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PYTHONDONTWRITEBYTECODE=1",
        "WORKDIR /app",
        "COPY pyproject.toml README.md ./",
        "COPY src ./src",
        f'RUN pip install --no-cache-dir "{install}"',
    ]
    copied = [package_dir(spec.module), *spec.include]
    for path in dict.fromkeys(copied):
        lines.append(f"COPY {path} ./{path}")
    if spec.requirements:
        lines.append(f"COPY {spec.requirements} ./requirements-target.txt")
        lines.append("RUN pip install --no-cache-dir -r requirements-target.txt")
    lines += [
        f"EXPOSE {spec.port}",
        f"HEALTHCHECK --interval=5s --timeout=5s --retries=30 CMD python -c \"{HEALTH_PROBE.format(port=spec.port)}\"",
        "CMD " + json.dumps(["evalbuilder", "serve", "--module", spec.module, "--factory", spec.factory, "--host", "0.0.0.0", "--port", str(spec.port)]),
        "",
    ]
    return "\n".join(lines)


def render_compose(spec: DeploymentSpec, dockerfile: str | Path) -> str:
    service = {
        "build": {"context": str(Path(spec.build_context).resolve()), "dockerfile": str(Path(dockerfile).resolve())},
        "image": spec.image,
        "ports": [f"{spec.host_port}:{spec.port}"],
        "environment": server_env(spec),
        "healthcheck": {
            "test": ["CMD", "python", "-c", HEALTH_PROBE.format(port=spec.port)],
            "interval": "5s", "timeout": "5s", "retries": 30, "start_period": "5s",
        },
    }
    doc = {"name": spec.resource, "services": {"agent": service}}
    return "# Generated by evalbuilder deploy\n" + yaml.safe_dump(doc, sort_keys=False)


def labels(spec: DeploymentSpec) -> dict[str, str]:
    return {"app": spec.resource, "app.kubernetes.io/managed-by": "evalbuilder"}


def render_manifests(spec: DeploymentSpec, image_pull_policy: str = "IfNotPresent") -> str:
    """Deployment + Service (NodePort under `expose: nodeport`) + Route (openshift, `expose: route`)."""
    meta = {"name": spec.resource, "namespace": spec.namespace, "labels": labels(spec)}
    container = {
        "name": "agent",
        "image": spec.image,
        "imagePullPolicy": image_pull_policy,
        "ports": [{"containerPort": spec.port, "name": "http"}],
        "env": [{"name": k, "value": v} for k, v in server_env(spec).items()],
        "readinessProbe": {"httpGet": {"path": "/health", "port": spec.port}, "periodSeconds": 3, "failureThreshold": 60},
        "livenessProbe": {"httpGet": {"path": "/health", "port": spec.port}, "periodSeconds": 15, "initialDelaySeconds": 30},
    }
    deployment = {
        "apiVersion": "apps/v1", "kind": "Deployment", "metadata": meta,
        "spec": {
            "replicas": spec.replicas,
            "selector": {"matchLabels": {"app": spec.resource}},
            "template": {"metadata": {"labels": labels(spec)}, "spec": {"containers": [container]}},
        },
    }
    service = {
        "apiVersion": "v1", "kind": "Service", "metadata": meta,
        "spec": {
            "type": "NodePort" if spec.expose == "nodeport" else "ClusterIP",
            "selector": {"app": spec.resource},
            "ports": [{"name": "http", "port": spec.port, "targetPort": spec.port}],
        },
    }
    docs = [deployment, service]
    if spec.expose == "route":
        docs.append({
            "apiVersion": "route.openshift.io/v1", "kind": "Route", "metadata": meta,
            "spec": {"to": {"kind": "Service", "name": spec.resource}, "port": {"targetPort": "http"}},
        })
    return "# Generated by evalbuilder deploy\n" + yaml.safe_dump_all(docs, sort_keys=False)


def render_loader(spec: DeploymentSpec) -> str:
    """The privileged DaemonSet that lets `docker save` be streamed into every node's
    containerd (`kubectl exec … nsenter -t 1 … ctr -n k8s.io images import -`)."""
    name = spec.resource + LOADER_SUFFIX
    ds = {
        "apiVersion": "apps/v1", "kind": "DaemonSet",
        "metadata": {"name": name, "namespace": spec.namespace, "labels": {"app": name, "app.kubernetes.io/managed-by": "evalbuilder"}},
        "spec": {
            "selector": {"matchLabels": {"app": name}},
            "template": {
                "metadata": {"labels": {"app": name}},
                "spec": {
                    "hostPID": True,
                    "tolerations": [{"operator": "Exists"}],
                    "containers": [{"name": "loader", "image": "busybox:1.36", "command": ["sleep", "infinity"],
                                    "securityContext": {"privileged": True}}],
                },
            },
        },
    }
    return "# Generated by evalbuilder deploy — image loader for clusters that cannot see local images\n" + yaml.safe_dump(ds, sort_keys=False)


def loader_name(spec: DeploymentSpec) -> str:
    return spec.resource + LOADER_SUFFIX
